// Builds shopify/assets/td-tiremath.js from the same source the React site
// uses. The tools on Shopify call exactly the functions that were checked
// against manufacturer specs — generated, never hand-copied, so the two
// cannot drift apart.
//
//   node scripts/build-shopify-assets.mjs
import { readFileSync, writeFileSync } from "node:fs";

const SOURCES = ["src/data/tireMath.js", "src/data/fitment.js"];
const OUT = "shopify/assets/td-tiremath.js";

const names = [];
let body = "";
for (const file of SOURCES) {
  let src = readFileSync(file, "utf8");
  // Both files are dependency-free; fail loudly if that ever stops being true.
  if (/^\s*import\s/m.test(src)) throw new Error(`${file} has an import; the asset build cannot bundle it`);
  src = src.replace(/^export\s+(function|const|let|class)\s+([A-Za-z_$][\w$]*)/gm, (_, kind, name) => {
    names.push(name);
    return `${kind} ${name}`;
  });
  if (/^\s*export\s/m.test(src)) throw new Error(`${file} has an export form this build does not handle`);
  body += `\n  // ---- ${file} ----\n` + src.replace(/^/gm, "  ") + "\n";
}

const out = `/* GENERATED by scripts/build-shopify-assets.mjs from ${SOURCES.join(", ")}.
 * Do not edit by hand — change the source and rebuild. */
(function () {
  "use strict";
${body}
  window.TireDrop = Object.freeze({ ${names.join(", ")} });
})();
`;
writeFileSync(OUT, out);
console.log(`wrote ${OUT}: ${names.length} exports → window.TireDrop`);
console.log("  " + names.join(", "));
